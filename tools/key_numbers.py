"""Generate results/KEY_NUMBERS.md: pitch-ready numbers, each a plain sentence + exact value + source.

    .venv\\Scripts\\python tools\\key_numbers.py           # write the file
    .venv\\Scripts\\python tools\\key_numbers.py --check   # exit 1 if the file differs from a fresh generation

Never edit KEY_NUMBERS.md by hand: every value is read from results/registry.csv, queue/decisions/, configs/ or
results/robustness/ and benchmark.json. Results that the queue has not produced yet are listed as pending.
tests/test_consistency.py fails if the committed file is stale.
"""
import csv
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from inference.system import system_name  # noqa: E402
sys.path.insert(0, str(ROOT))
from backend import experiments  # noqa: E402
OUT = ROOT / "results/KEY_NUMBERS.md"
README = ROOT / "README.md"
START, END = "<!-- KEY-NUMBERS:START (generated by tools/key_numbers.py) -->", "<!-- KEY-NUMBERS:END -->"
HEADLINE = ("Agreement with eye specialists", "within one stage", "Referable DR caught", "Share of the worklist read",
            "Images the AI defers", "confident stage")
SPLITS = {"idrid_grading_val": "IDRiD-val", "aptos_val": "APTOS-val"}
LESIONS = {"MA": "microaneurysms", "HE": "haemorrhages", "EX": "hard exudates", "SE": "soft exudates"}


def pct(v, d=0):
    return f"{100 * v:.{d}f}%"


def load():
    rows = list(csv.DictReader(open(ROOT / "results/registry.csv", encoding="utf-8")))
    app = json.loads((ROOT / "configs/app/app.json").read_text())
    return rows, app


def latest(rows, **kw):
    hits = [r for r in rows if all(r[k] == v for k, v in kw.items())]
    return hits[-1] if hits else None


def jfile(rel):
    p = ROOT / rel
    return json.loads(p.read_text()) if p.exists() else None


def generate():
    rows, app = load()
    g = system_name(app)  # registry name of the app's grading system
    lines = []

    def add(section, sentence, value, source):
        lines.append((section, sentence, value, source))

    # Grading
    for split, name in SPLITS.items():
        r = latest(rows, task="grade", model=g, eval_split=split)
        if r:
            add("Grading", f"Agreement with eye specialists on {name} (quadratic weighted kappa; 1 = perfect)", f"{float(r['qwk']):.3f} [{r['qwk_ci']}]", f"registry {r['run_id']}")
    for split, name in SPLITS.items():
        r = latest(rows, task="agreement", model=g, eval_split=split)
        if r:
            m = jfile(f"results/runs/{r['run_id']}/metrics.json")
            add("Grading", f"AI stage within one stage of the specialist's grade, {name}", pct(m["point"]["within_one"], 1), f"registry {r['run_id']}")
            add("Grading", f"AI stage exactly the specialist's grade, {name}", pct(m["point"]["accuracy"], 1), f"registry {r['run_id']}")
            add("Grading", f"Referable DR caught (sensitivity at AI stage ≥ 2), {name}", pct(m["point"]["referable_sens"], 1), f"registry {r['run_id']}")
            add("Grading", f"Non-referable correctly cleared (specificity), {name}", pct(m["point"]["referable_spec"], 1), f"registry {r['run_id']}")
    for name in ("a2_swap", "a2_ensemble", "pseudo_label", "a4_fusion"):
        d = jfile(f"queue/decisions/{name}.json")
        if d:
            q = "; ".join(f"{SPLITS.get(s, s)} ΔQWK {v['delta']['qwk']['point']:+.3f} [{v['delta']['qwk']['ci95'][0]:+.3f}, {v['delta']['qwk']['ci95'][1]:+.3f}]"
                          for s, v in d["splits"].items())
            add("Model decisions", f"{d['adr']} {name}: {'adopted' if d.get('app_grader_switched') else 'not adopted'} ({'rule passed' if d['verdict']['passed'] else 'rule not met'})",
                q, f"queue/decisions/{name}.json")
        elif name != "a2_swap":
            add("Model decisions", f"{name}", "pending", "GPU queue")

    # Calibration, deferral, worklist
    cal = jfile("configs/calibration/app_grader.json")
    if cal and cal.get("grader") == g and not app.get("fusion"):
        for split, name in SPLITS.items():
            v = cal["validation"][split]
            add("Worklist and deferral", f"Referable-DR ranking quality (AUROC), {name}", f"{v['triage']['auroc']:.3f}", "configs/calibration/app_grader.json")
            add("Worklist and deferral", f"Share of the worklist read to find 95% of referable cases, {name} (random order: 95%)",
                pct(v["triage"]["workload_to_95pct_sensitivity"]), "configs/calibration/app_grader.json")
            add("Worklist and deferral", f"Images the AI defers to a human grader, {name}", pct(1 - v["abstention"]["coverage"], 1), "configs/calibration/app_grader.json")
            add("Worklist and deferral", f"Calibration error of P(referable), uncalibrated → calibrated, {name} (ECE)",
                f"{v['ece_p_referable']['before']:.3f} → {v['ece_p_referable']['after']:.3f}", "configs/calibration/app_grader.json")
    else:
        add("Worklist and deferral", "Calibration, deferral and worklist metrics for the current grader", "pending", "GPU queue (b5b6 job)")

    # Routine-rescreening routing (Approach V2, ADR-039/040): policy (c), images; development data only
    cov = [r for r in rows if r["task"] == "coverage"]
    if cov:
        m = jfile(f"results/runs/{cov[-1]['run_id']}/metrics.json")
        cfg = jfile("configs/routing/routing_v1.json")
        for lvl in cfg["thresholds"]:
            for name, v in m["validation"].items():
                c = v["c"][lvl]
                add("Routine-rescreening routing (development data)", f"Images routed to routine rescreening at a {float(lvl) * 100:g}% target miss rate, {name} (95% CI)",
                    f"{pct(c['coverage'], 1)} [{pct(c['coverage_ci95'][0], 1)}–{pct(c['coverage_ci95'][1], 1)}]", f"registry {cov[-1]['run_id']}")
                add("Routine-rescreening routing (development data)", f"Referable images routed to routine (missed), {float(lvl) * 100:g}% target, {name}; exact 95% upper bound",
                    f"{c['missed']}/{c['referable']}; ≤ {pct(c['miss_rate_upper95'], 1)}", f"registry {cov[-1]['run_id']}")
        add("Routine-rescreening routing (development data)", "Default operating point (not yet validated on external data)",
            f"{float(cfg['default_target']) * 100:g}% target; verified upper bound {pct(cfg['verified'][str(cfg['default_target'])]['APTOS-val']['upper95'], 1)} on APTOS-val",
            "configs/routing/routing_v1.json")
    else:
        add("Routine-rescreening routing (development data)", "Coverage of the routine-rescreening pile", "pending", "tools/coverage_step2.py")

    # Step 4 experiments (ADR-041): verdicts and what was found, development data
    for e in experiments.rows():
        add("Step 4 experiments (development data)", f"{e['name']}: {e['verdict']}", e["found"], "results/step4, results/faithfulness.json, results/robustness")

    # Segmentation
    seg = app.get("segmenter") or {k: dict(model="v0", postprocess="configs/postprocess/pp_v2.json") for k in LESIONS}
    for l, lname in LESIONS.items():
        model = f"{seg[l]['model']}+{Path(seg[l]['postprocess']).stem}"
        for split, sname in (("idrid_seg_val", "IDRiD-val"), ("ddr_seg_test", "DDR-test")):
            r = latest(rows, task="segment", model=model, eval_split=split)
            if r and r[f"aupr_{l}"]:
                add("Lesion segmentation", f"Pixel AUPR for {lname}, {sname} ({'A3' if model.startswith('a3:') else 'v0.1'} segmenter)",
                    f"{float(r[f'aupr_{l}']):.3f}", f"registry {r['run_id']}")
    d = jfile("queue/decisions/a3_swap.json")
    add("Lesion segmentation", "A3 segmentation swap (ADR-016, per lesion)",
        ("lesions swapped: " + (", ".join(d["lesions_swapped"]) or "none")) if d else "pending", "queue/decisions/a3_swap.json" if d else "GPU queue")

    # Macular edema
    rule = jfile(app.get("dme_rule", "configs/landmarks/dme_rule_v1.json"))
    v = rule["val"]
    add("Macular-edema rule", "High-risk macular edema caught (sensitivity), IDRiD-val", pct(v["high_risk_sensitivity"]), app.get("dme_rule", "configs/landmarks/dme_rule_v1.json"))
    add("Macular-edema rule", "High-risk flags that are correct (PPV), IDRiD-val", pct(v["high_risk_ppv"]), app.get("dme_rule", "configs/landmarks/dme_rule_v1.json"))

    # Safety
    r2 = jfile("results/robustness/r2_bad_input.json")
    add("Safety", "Non-fundus, blurred or very dark images given a confident stage (must be 0)",
        f"{len(r2['failures'])} of {r2['n']}" if r2 else "pending", "results/robustness/r2_bad_input.json" if r2 else "GPU queue")
    r1 = jfile("results/robustness/r1_robustness.json")
    if r1:
        for split, name in SPLITS.items():
            res = r1["results"][split]
            worst = min(((k, x["qwk"]) for k, x in res.items() if x["qwk"] is not None), key=lambda t: t[1])
            add("Safety", f"QWK on clean images vs worst tested degradation ({worst[0]}), {name}", f"{res['none_0']['qwk']:.3f} → {worst[1]:.3f}",
                "results/robustness/r1_robustness.json")
    else:
        add("Safety", "Robustness to blur, darkness, JPEG, downscaling, rotation", "pending", "GPU queue")
    r3 = jfile("results/robustness/r3_gradcam_audit.json")
    add("Safety", "Grad-CAM peaks on border, optic disc or glare (IDRiD-val / APTOS-val)",
        " / ".join(pct(r3["results"][s]["shortcut_fraction"], 1) for s in SPLITS) if r3 else "pending",
        "results/robustness/r3_gradcam_audit.json" if r3 else "GPU queue")
    r4 = jfile("results/robustness/r4_quality_gate.json")
    add("Safety", "DDR ungradable images flagged by the quality gate / gradable images wrongly flagged",
        f"{pct(r4['results']['ungradable']['flagged'], 1)} / {pct(r4['results']['gradable']['flagged'], 1)}" if r4 else "pending",
        "results/robustness/r4_quality_gate.json" if r4 else "GPU queue")

    # Speed
    b = jfile("results/benchmark.json")
    ok = b and "per_stage" in b.get("gpu", {}) and "per_stage" in b.get("cpu", {})
    add("Speed", "Full analysis time per image, GPU / CPU (RS_DEVICE=cpu)",
        f"{b['gpu']['per_stage']['total']['mean_s']:.2f} s / {b['cpu']['per_stage']['total']['mean_s']:.2f} s" if ok else "pending",
        "results/benchmark.json" if b else "tools/benchmark.py")
    add("Speed", "One patient (two eyes) through the app, GPU / CPU",
        f"{b['gpu']['per_patient_two_eyes']['mean_s']:.2f} s / {b['cpu']['per_patient_two_eyes']['mean_s']:.2f} s" if ok else "pending",
        "results/benchmark.json" if b else "tools/benchmark.py")

    # Locked evaluation of rc-1 (ADR-043): run once per set, reported whatever the result
    for name, label in (("idrid_test", "IDRiD clean test (102 images)"), ("deepdrid", "DeepDRiD (1,988 images, 500 patients)")):
        L = jfile(f"results/locked/{name}.json")
        if not L:
            add("Locked evaluation of rc-1", f"{label}", "pending", "tools/locked_eval.py")
            continue
        g = L.get("grading") or L["primary_image_level"]["grading"]
        ri = L.get("routing_images") or L["primary_image_level"]["routing_images"]
        ci = g["ci95"]
        add("Locked evaluation of rc-1", f"{label}: QWK (95% CI)", f"{g['qwk']:.3f} [{ci['qwk'][0]:.3f}–{ci['qwk'][1]:.3f}]", f"results/locked/{name}.json")
        add("Locked evaluation of rc-1", f"{label}: referable sensitivity / specificity (95% CI)",
            f"{pct(g['referable_sensitivity'], 1)} [{pct(ci['referable_sensitivity'][0], 1)}–{pct(ci['referable_sensitivity'][1], 1)}] / "
            f"{pct(g['referable_specificity'], 1)} [{pct(ci['referable_specificity'][0], 1)}–{pct(ci['referable_specificity'][1], 1)}]", f"results/locked/{name}.json")
        add("Locked evaluation of rc-1", f"{label}: images routed to routine at 2.5%; referable routed to routine (exact 95% upper bound)",
            f"{pct(ri['coverage'], 1)} [{pct(ri['coverage_ci95'][0], 1)}–{pct(ri['coverage_ci95'][1], 1)}]; {ri['missed']}/{ri['referable']} (≤ {pct(ri['miss_rate_upper95'], 1)})",
            f"results/locked/{name}.json")
        if "patient_level_routing" in L:
            pl = L["patient_level_routing"]
            add("Locked evaluation of rc-1", f"{label}: patients routed to routine at 2.5%; referable patients routed to routine (exact 95% upper bound)",
                f"{pct(pl['coverage'], 1)} [{pct(pl['coverage_ci95'][0], 1)}–{pct(pl['coverage_ci95'][1], 1)}]; {pl['missed']}/{pl['referable']} (≤ {pct(pl['miss_rate_upper95'], 1)})",
                f"results/locked/{name}.json")
            q = L["quality_gate"]
            add("Locked evaluation of rc-1", f"{label}: quality-gate agreement with DeepDRiD quality labels; poor-quality images flagged",
                f"{pct(q['accuracy'], 1)}; {pct(q['flag_rate_among_poor'], 1)}", f"results/locked/{name}.json")

    out = ["# Key numbers", "",
           f"Generated by `tools/key_numbers.py` for app {app['version']}. Do not edit by hand; every value has a source.",
           "Grading numbers are on held-out validation sets unless the section says \"Locked evaluation of rc-1\" (run once, ADR-043). "
           "The IDRiD segmentation test and Messidor-2 have not been used.", ""]
    section = None
    for sec, sentence, value, source in lines:
        if sec != section:
            out += ["", f"## {sec}", "", "| What | Value | Source |", "|---|---|---|"]
            section = sec
        out.append(f"| {sentence} | {value} | `{source}` |")
    head = ["| What | Value |", "|---|---|"] + [f"| {sentence} | {value} |" for _, sentence, value, _ in lines
                                                  if any(h in sentence for h in HEADLINE)]
    return "\n".join(out) + "\n", "\n".join(head)


def readme_with(head):
    text = README.read_text(encoding="utf-8")
    i, j = text.index(START), text.index(END)
    return (text[:i + len(START)] + "\n" + head + "\n\nAll values and their sources: [results/KEY_NUMBERS.md](results/KEY_NUMBERS.md).\n"
            + text[j:])


def main():
    text, head = generate()
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        sys.exit(0 if current == text and README.read_text(encoding="utf-8") == readme_with(head) else 1)
    OUT.write_text(text, encoding="utf-8")
    README.write_text(readme_with(head), encoding="utf-8")
    print(f"RESULT: wrote {OUT.relative_to(ROOT)} ({text.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
